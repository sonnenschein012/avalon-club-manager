export type StudioMessage = keyof typeof korean;
export function useStudioText() {
  const language = useStudioLanguage();
  return (message: StudioMessage) => language === 'ko' ? korean[message] : message;
}

export function studioImageError(error: unknown): StudioMessage {
  const message = error instanceof Error ? error.message : '';
  return message === 'Choose a PNG, JPEG, or WebP file under 16 MB.' ||
    message === 'Image processing is unavailable in this browser.' ||
    message === 'This image could not be resized for the exhibit.' ? message : 'Could not prepare this image.';
}

